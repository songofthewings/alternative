    @Action
    public void addSubaimAction() {
        try {
            controller.addAim(aimTree);
            this.repaint();
        } catch (HierarchyException he) {
            messager.warn(he, resourceBundle.getString("PLEASE_CORRECT_THIS_BEFORE_SAVING"));
        }
    }

    @Action
    public void editAimAction() {
        aimTree.startEditingTarget();
    }

    @Action
    public void removeAimAction() {
        try {
            aimTree.removeSelected();
        } catch (NothingSelectedException he) {
            messager.warn(he, resourceBundle.getString("THERE_WERE_PROBLEMS_WHILE_REMOVING"));
        }
    }

    @Action
    public void addAlternativeAction() {
        controller.addAlternative(alternativesList);
        this.repaint();
    }

    @Action
    public void editAlternativeAction() {
        alternativesList.startEditingTarget();
    }

    @Action
    public void removeAlternativeAction() {
        try {
            alternativesList.removeSelected();
        } catch (NothingSelectedException he) {
            messager.warn(he, resourceBundle.getString("THERE_WERE_PROBLEMS_WHILE_REMOVING"));
        }
    }

    public TreeModel getTreeModel() {
        return this.getTree(this.problemName);
    }

    public TreeModel getAlternativesModel() {
        return this.getAlternativesModel(this.problemName);
    }

    public void loadProblem(String problemName) {
        aimTree.setModel(this.getTree(problemName));
        alternativesList.setModel(this.getAlternativesModel(problemName));
    }
    public TreeModel getTree(String problemName) {
        this.problemName = problemName;
        this.setTitle(
                (null == problemName) ? resourceBundle.getString("CREATING_A_NEW_CHOICE_AIM-CRITERIA_TREE")
                                     : resourceBundle.getString("EDITING_AN_AIM-CRITERIA_TREE")
                    );
        try {
            return this.controller.getHierarchyModel(problemName);
        } catch (JAXBException je) {
            messager.log(je);
        }catch (IOException ioe) {
            messager.error(ioe, resourceBundle.getString("ERROR_WHILE_RESTORING_AIM-CRITERIA_TREE"));
        }
        return controller.getNewTreeModel();
    }

    public TreeModel getAlternativesModel(String problemName) {
        try {
            TreeModel tm = this.controller.getAlternativesListModel(problemName);
            return tm;
        } catch (JAXBException je) {
            messager.log(je);
        }catch (IOException ioe) {
            messager.error(ioe, resourceBundle.getString("ERROR_WHILE_RESTORING_ALTERNATIVES_LIST"));
        }
        return controller.getNewAlternativesModel();
    }

    @Action
    public void saveTreeAndContinue() {
        try {
            this.controller.store((AimTreeModel) aimTree.getModel(),
                    alternativesList.getModel());
            this.dispose();
        } catch (FileNotFoundException ex) {
            messager.log(ex);
        } catch (JAXBException ex) {
            messager.log(ex);
        } catch (IOException ioe) {
            messager.error(ioe, resourceBundle.getString("ERROR_WHILE_SAVING_AIM-CRITERIA_TREE"));
        }catch (HierarchyException he) {
            messager.warn(he, resourceBundle.getString("PLEASE_CORRECT_THIS_BEFORE_SAVING"));
        }
    }

    @Action
    public void cancel() {
        this.dispose();
    }

