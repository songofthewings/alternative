    /** Creates new form PriorityChooser */
    public PriorityChooser(java.awt.Frame parent, boolean modal, Priority currentPriority, ActionListener applyButtonListener) {
        super(parent, modal);

        this.priority = currentPriority.getCopy();

        initComponents();

        applyButton.addActionListener(applyButtonListener);
        prioritySlider.addChangeListener(new ChangeListener() {
                @Override
                public void stateChanged(ChangeEvent e) {
                    Object source = e.getSource();
                    if (source instanceof JSlider) {
                        JSlider pSlider = (JSlider) source;
                        try {
                            double value = pSlider.getValue();
                            double dividend = (pSlider.getMaximum()-value);
                            double divider = (value-pSlider.getMinimum());

                            if (Math.round(divider) < BOUND_TICK ) {
                                divider = BOUND_TICK;
                                dividend -= BOUND_TICK;
                            }
                            if (Math.round(dividend) < BOUND_TICK) {
                                dividend = BOUND_TICK;
                                divider -= BOUND_TICK;
                            }
                            priority.setValue(dividend / divider);
                            messageLabel.setText(getMessage());
                        } catch (PriorityException pe) {
                            Logger.getLogger(PriorityChooser.class.getName()).log(Level.SEVERE, 
                                    "Wrong Priority value by JSlider: value = " + pSlider.getValue() 
                                    + " max = " +  pSlider.getMaximum(), pe);
                        }
                    }
                }
            });
    }

    protected String getMessage() {
        return priority.toString();
    }

    public Priority getPriority() {
        return priority;
    }

    public void setPriority(Priority priority) {
        this.priority = priority.getCopy();
        int max = prioritySlider.getMaximum();
        int min = prioritySlider.getMinimum();
        prioritySlider.setValue((int) Math.round(min + ((double) (max-min))
                                                        /(this.priority.getValue() + 1)));
        messageLabel.setText(getMessage());
    }

    @Action
    public void cancel() {
        this.setVisible(false);
    }

